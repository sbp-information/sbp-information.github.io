'use strict';
// Deterministic, dependency-free CSS bundler.
// The source stylesheet order mirrors the previously deployed index.html.
// Keep the desktop-only sheet scoped to its original media query.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const bundles = {
  'sbp-core.css': [
    'style.css',
    'desktop.css',
    'gradients.css',
    'responsive-fit.css',
    'soft-frames.css',
    'home-overview.css',
    'group-banners.css',
    'redesign.css',
    'site-improvements.css',
    'dark-mode.css',
    'compact-layout.css'
  ],
  'sbp-ui.css': [
    'home-first-reference.css',
    'approved-interface.css',
    'targeted-header-fixes.css',
    'home-header-alignment.css',
    'desktop-header-align.css',
    'secondary-header-alignment.css',
    'home-equal-lesson-cards.css',
    'journal-flat-status.css',
    'schedule-break-alignment.css',
    'mobile-menu-hit-target.css',
    'brand-blue.css'
  ]
};
function bundleContents(files) {
  let content = '/* Auto-generated by node scripts/build-css.cjs. Edit source .css files, not this bundle. */\n';
  for (const file of files) {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    if (/^\s*@(import|charset)\b/m.test(source)) {
      throw new Error(file + ' contains an @import/@charset that cannot be combined in this position');
    }
    const body = source.endsWith('\n') ? source : source + '\n';
    content += '\n/* === ' + file + ' === */\n';
    content += file === 'desktop.css' ? '@media (min-width: 768px) {\n' + body + '}\n' : body;
  }
  return content;
}
const check = process.argv.includes('--check');
for (const [name, files] of Object.entries(bundles)) {
  const file = path.join(root, name);
  const expected = bundleContents(files);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== expected) {
      throw new Error(name + ' is stale. Run: node scripts/build-css.cjs');
    }
  } else fs.writeFileSync(file, expected);
  console.log(name + ': ' + files.length + ' source sheets, ' + Buffer.byteLength(expected) + ' bytes');
}
module.exports = { bundles, bundleContents };
